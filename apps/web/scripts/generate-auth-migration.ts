import { DatabaseSync } from "node:sqlite";
import { mkdir, writeFile } from "node:fs/promises";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../src/lib/auth/options";

// Generate the initial SQLite schema offline; Wrangler applies it to D1.
const database = new DatabaseSync(":memory:");
const migrations = await getMigrations({
  ...authOptions({
    baseURL: "http://localhost:3000",
    googleClientId: "schema-generation",
    googleClientSecret: "schema-generation",
    secret: "schema-generation-only-not-a-runtime-secret",
  }),
  database,
});
await mkdir(new URL("../migrations/", import.meta.url), { recursive: true });
await writeFile(
  new URL("../migrations/0001_auth.sql", import.meta.url),
  `-- Generated by scripts/generate-auth-migration.ts.\n${await migrations.compileMigrations()}\n`,
);
database.close();
